import 'package:feature_pokemon/feature_pokemon.dart';
import 'package:go_router/go_router.dart';
import 'package:material_ui/material_ui.dart';
import 'package:pokemon_app/home_page.dart';

part 'app_routes.g.dart';

/// Public route names/paths for the app, kept alongside the typed route data
/// classes below. Mirrors the reference's `Routes`/`_Paths` split.
class Routes {
  Routes._();

  static const String home = _Paths.home;
  static const String pokemonList = _Paths.pokemonList;

  /// Concrete `/pokemon/{name}` path for a given Pokemon.
  static String pokemonDetail(String name) => '${_Paths.pokemonList}/$name';
}

class _Paths {
  _Paths._();

  static const String home = '/';
  static const String pokemonList = '/pokemon';
}

/// Home (`/`) with the Pokemon list (`/pokemon`) and detail (`/pokemon/:name`)
/// nested underneath. Route table generated by `go_router_builder`.
@TypedGoRoute<HomeRoute>(
  path: _Paths.home,
  routes: [
    TypedGoRoute<PokemonListRoute>(
      path: 'pokemon',
      routes: [TypedGoRoute<PokemonDetailRoute>(path: ':name')],
    ),
  ],
)
class HomeRoute extends GoRouteData with $HomeRoute {
  const HomeRoute();

  @override
  Widget build(BuildContext context, GoRouterState state) => const HomePage();
}

/// `/pokemon` — the paginated Pokemon list.
class PokemonListRoute extends GoRouteData with $PokemonListRoute {
  const PokemonListRoute();

  @override
  Widget build(BuildContext context, GoRouterState state) =>
      const PokemonPage();
}

/// `/pokemon/:name` — detail for a single Pokemon.
class PokemonDetailRoute extends GoRouteData with $PokemonDetailRoute {
  const PokemonDetailRoute({required this.name});

  final String name;

  @override
  Widget build(BuildContext context, GoRouterState state) =>
      PokemonDetailPage(name: name);
}
